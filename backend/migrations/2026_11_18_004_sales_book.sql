-- Trade Management (sales): quotations, sales orders and delivery notes to customers.
-- Each document has a header row and its item lines, priced as purchase order lines (price, VAT %, discount)
-- plus a delivery term per line. Lines keep the item code, name, brand and unit as text too.
-- A sales order can come from a quotation, a delivery note from a sales order.
-- Applied by backend/bin/migrate.php. MySQL 8 / MariaDB 10.6+.

CREATE TABLE quotations (
  id                INT UNSIGNED  NOT NULL AUTO_INCREMENT,
  qt_code           VARCHAR(20)   NOT NULL,
  qt_date           DATE          NOT NULL,
  reference_no      VARCHAR(60)   NOT NULL DEFAULT '',
  customer_id       INT UNSIGNED  NULL,
  contact_name      VARCHAR(100)  NOT NULL DEFAULT '',
  contact_number    VARCHAR(40)   NOT NULL DEFAULT '',
  currency          VARCHAR(10)   NOT NULL DEFAULT 'OMR',
  delivery_location VARCHAR(200)  NOT NULL DEFAULT '',
  offer_validity    VARCHAR(40)   NOT NULL DEFAULT '',
  payment_mode      VARCHAR(40)   NOT NULL DEFAULT '',
  credit_period     VARCHAR(40)   NOT NULL DEFAULT '',
  salesman          VARCHAR(100)  NOT NULL DEFAULT '',
  salesman_contact  VARCHAR(40)   NOT NULL DEFAULT '',
  certifications    VARCHAR(200)  NOT NULL DEFAULT '',
  vat_mode          VARCHAR(10)   NOT NULL DEFAULT 'exclude',
  subtotal          DECIMAL(14,3) NOT NULL DEFAULT 0,
  vat_amount        DECIMAL(14,3) NOT NULL DEFAULT 0,
  discount_amount   DECIMAL(14,3) NOT NULL DEFAULT 0,
  shipping          DECIMAL(14,3) NOT NULL DEFAULT 0,
  grand_total       DECIMAL(14,3) NOT NULL DEFAULT 0,
  remarks           TEXT          NULL,
  include_signatory TINYINT(1)    NOT NULL DEFAULT 0,
  extra_signatories TEXT          NULL,
  attach_seal       TINYINT(1)    NOT NULL DEFAULT 0,
  created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_quotations_code (qt_code),
  CONSTRAINT fk_quotations_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE sales_orders (
  id                INT UNSIGNED  NOT NULL AUTO_INCREMENT,
  so_code           VARCHAR(20)   NOT NULL,
  so_date           DATE          NOT NULL,
  quotation_id      INT UNSIGNED  NULL,
  customer_po       VARCHAR(60)   NOT NULL DEFAULT '',
  customer_id       INT UNSIGNED  NULL,
  contact_name      VARCHAR(100)  NOT NULL DEFAULT '',
  contact_number    VARCHAR(40)   NOT NULL DEFAULT '',
  currency          VARCHAR(10)   NOT NULL DEFAULT 'OMR',
  delivery_location VARCHAR(200)  NOT NULL DEFAULT '',
  delivery_date     DATE          NULL,
  payment_mode      VARCHAR(40)   NOT NULL DEFAULT '',
  credit_period     VARCHAR(40)   NOT NULL DEFAULT '',
  salesman          VARCHAR(100)  NOT NULL DEFAULT '',
  salesman_contact  VARCHAR(40)   NOT NULL DEFAULT '',
  vat_mode          VARCHAR(10)   NOT NULL DEFAULT 'exclude',
  subtotal          DECIMAL(14,3) NOT NULL DEFAULT 0,
  vat_amount        DECIMAL(14,3) NOT NULL DEFAULT 0,
  discount_amount   DECIMAL(14,3) NOT NULL DEFAULT 0,
  shipping          DECIMAL(14,3) NOT NULL DEFAULT 0,
  grand_total       DECIMAL(14,3) NOT NULL DEFAULT 0,
  advance_payment   DECIMAL(14,3) NOT NULL DEFAULT 0,
  remarks           TEXT          NULL,
  include_signatory TINYINT(1)    NOT NULL DEFAULT 0,
  extra_signatories TEXT          NULL,
  attach_seal       TINYINT(1)    NOT NULL DEFAULT 0,
  created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_sales_orders_code (so_code),
  CONSTRAINT fk_sales_orders_quotation FOREIGN KEY (quotation_id) REFERENCES quotations (id) ON DELETE RESTRICT,
  CONSTRAINT fk_sales_orders_customer  FOREIGN KEY (customer_id)  REFERENCES customers (id)  ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

