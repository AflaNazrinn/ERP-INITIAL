) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE quotation_items (
  id              INT UNSIGNED  NOT NULL AUTO_INCREMENT,
  quotation_id    INT UNSIGNED  NOT NULL,
  sort_order      INT           NOT NULL DEFAULT 0,
  item_id         INT UNSIGNED  NULL,
  item_code       VARCHAR(30)   NOT NULL DEFAULT '',
  item_name       VARCHAR(200)  NOT NULL,
  item_name_html  TEXT          NULL,
  brand_id        INT UNSIGNED  NULL,
  brand_name      VARCHAR(150)  NOT NULL DEFAULT '',
  delivery_term   VARCHAR(200)  NOT NULL DEFAULT '',
  quantity        DECIMAL(14,3) NOT NULL,
  uom_id          INT UNSIGNED  NULL,
  unit            VARCHAR(80)   NOT NULL DEFAULT '',
  price           DECIMAL(14,3) NOT NULL DEFAULT 0,
  vat_rate        DECIMAL(5,2)  NOT NULL DEFAULT 5,
  discount_pct    DECIMAL(5,2)  NOT NULL DEFAULT 0,
  discount_amount DECIMAL(14,3) NOT NULL DEFAULT 0,
  foc             TINYINT(1)    NOT NULL DEFAULT 0,
  line_total      DECIMAL(14,3) NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  KEY idx_quotation_items_doc (quotation_id),
  CONSTRAINT fk_quotation_items_doc   FOREIGN KEY (quotation_id) REFERENCES quotations (id) ON DELETE CASCADE,
  CONSTRAINT fk_quotation_items_item  FOREIGN KEY (item_id)  REFERENCES items (id)  ON DELETE RESTRICT,
  CONSTRAINT fk_quotation_items_brand FOREIGN KEY (brand_id) REFERENCES brands (id) ON DELETE RESTRICT,
  CONSTRAINT fk_quotation_items_uom   FOREIGN KEY (uom_id)   REFERENCES uoms (id)   ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

